export function Journal() {
  const { data, error, loading } = useResource<{ articles: Article[]; offers: Offer[] }>('catalog');
  return (
    <>
      <section className="info-hero">
        <span className="eyebrow">مجله سفر برجیس</span>
        <h1>روایت‌هایی برای راه افتادن</h1>
        <p>مقصدها، تجربه‌ها و نکته‌هایی برای سفر آگاهانه‌تر.</p>
      </section>
      <div className="container page-pad">
        {error && <div className="inline-error">{error}</div>}
        <div className="journal-grid">
          {loading
            ? [1, 2, 3].map((i) => <div className="skeleton" style={{ height: 350 }} key={i} />)
            : data?.articles.map((a) => (
                <Link className="journal-card" href={`/journal/${a.id}`} key={a.id}>
                  <div className="journal-image">
                    <Image
                      src={a.image}
                      fill
                      sizes="(max-width:600px) 50vw,33vw"
                      alt="تصویر الهام‌بخش سفر"
                    />
                  </div>
                  <div>
                    <span className="eyebrow">راهنمای سفر</span>
                    <h3>{a.title}</h3>
                    <p>{a.excerpt}</p>
                    <span className="text-link small">
                      ادامه روایت <ArrowUpLeft size={15} />
                    </span>
                  </div>
                </Link>
              ))}
        </div>
      </div>
    </>
  );
}
export function JournalArticle({ id }: { id: string }) {
  const { data, error, loading } = useResource<Article>(`articles/${id}`);
  if (loading)
    return (
      <div className="container page-pad">
        <div className="skeleton" style={{ height: 400 }} />
      </div>
    );
  if (error || !data)
    return (
      <div className="container page-pad">
        <div className="empty-state">
          <p>{error}</p>
          <Link href="/journal">بازگشت به مجله</Link>
        </div>
      </div>
    );
  return (
    <>
      <section className="info-hero">
        <span className="eyebrow">مجله برجیس · راهنمای سفر</span>
        <h1>{data.title}</h1>
        <p>{data.excerpt}</p>
      </section>
      <article className="prose">
        <div className="article-cover">
          <Image src={data.image} fill sizes="800px" alt="تصویر الهام‌بخش مقاله" />
        </div>
        <p style={{ whiteSpace: 'pre-line' }}>{data.body}</p>
        <div className="notice-box">
          اطلاعات مقاله عمومی است؛ قوانین روز ورود، مدارک و خدمات را از مراجع رسمی بررسی کنید.
          تصاویر الهام‌بخش‌اند.
        </div>
        <Button asChild variant="outline">
          <Link href="/journal">بازگشت به مجله</Link>
        </Button>
      </article>
    </>
  );
}
